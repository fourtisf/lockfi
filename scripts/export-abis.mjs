#!/usr/bin/env node
// Writes lib/contracts/abis.ts from the Foundry build in contracts/out, so
// the site and the keeper call the contracts with the ABIs they were built
// from. Run after `forge build`:  node scripts/export-abis.mjs
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
// [source file, contract]
const CONTRACTS = [
  ['TidewellVault', 'TidewellVault'],
  ['TidewellZap', 'TidewellZap'],
  ['TidewellShaper', 'TidewellShaper'],
  ['TidewellRouter', 'TidewellRouter'],
  ['TidewellRouter', 'TidewellRouterFactory'],
];

let out = `// Generated by scripts/export-abis.mjs from contracts/out. Do not edit.\n`;
for (const [file, name] of CONTRACTS) {
  let artifact;
  try {
    artifact = JSON.parse(readFileSync(join(root, 'contracts/out', `${file}.sol`, `${name}.json`), 'utf8'));
  } catch {
    console.warn(`skip ${name}: not built`);
    continue;
  }
  const id = name.charAt(0).toLowerCase() + name.slice(1);
  out += `\nexport const ${id}Abi = ${JSON.stringify(artifact.abi, null, 2)} as const;\n`;
}
const file = join(root, 'lib/contracts/abis.ts');
mkdirSync(dirname(file), { recursive: true });
writeFileSync(file, out);
console.log(`wrote ${file}`);
